"""``bernstein init`` interactive wizard.

Ask questions and generate bernstein.yaml interactively.
"""

from __future__ import annotations

import json
from pathlib import Path

import click

from bernstein.cli.helpers import SDD_DIRS, console, find_seed_file
from bernstein.core.identity import install_rev as _identity
from bernstein.core.identity.install_rev import (
    DISABLED_SENTINEL,
    render_yaml_comment,
)

# ---------------------------------------------------------------------------
# Project type detection
# ---------------------------------------------------------------------------

_PROJECT_INDICATORS: dict[str, list[str]] = {
    "python": ["pyproject.toml", "setup.py", "setup.cfg", "requirements.txt"],
    "node": ["package.json"],
    "rust": ["Cargo.toml"],
    "go": ["go.mod"],
    "java": ["pom.xml", "build.gradle"],
    "ruby": ["Gemfile"],
}


def detect_project_type(root: Path) -> str:
    """Detect project type from marker files."""
    for ptype, markers in _PROJECT_INDICATORS.items():
        for marker in markers:
            if (root / marker).exists():
                return ptype
    return "generic"


# ---------------------------------------------------------------------------
# YAML generation
# ---------------------------------------------------------------------------


def generate_yaml(
    goal: str,
    project_type: str,
    max_agents: int,
    budget: float,
    adapter: str,
    approval: str,
) -> str:
    """Generate bernstein.yaml content from wizard answers.

    Args:
        goal: Project goal.
        project_type: Detected project type.
        max_agents: Maximum concurrent agents.
        budget: Cost cap in USD.
        adapter: Preferred adapter (auto/claude/codex/gemini).
        approval: Approval mode (auto/review/pr).

    Returns:
        YAML content string.
    """
    lines: list[str] = []
    # Optional install-rev fingerprint.  Lands as the first comment so
    # the operator's GitHub code search picks it up uniformly
    # regardless of any subsequent yaml resaves that may strip later
    # comments.  Skipped entirely when emission is off or the token is
    # the disabled sentinel - we never emit a useless ``0…0`` placeholder
    # in the user's repo.
    if _identity.IDENTITY_EMISSION_ENABLED:
        token_line = render_yaml_comment()
        if DISABLED_SENTINEL not in token_line:
            lines.append(token_line)
    merge_strategy = "direct" if approval == "auto" else "pr"
    auto_merge = approval == "auto"
    lines.extend(
        [
            "# Bernstein configuration -- generated by 'bernstein init'",
            f"# Project type: {project_type}",
            "",
            f"goal: {json.dumps(goal, ensure_ascii=False)}",
            f"cli: {adapter}",
            f"max_agents: {max_agents}",
            f"budget: {budget:.2f}",
            f"merge_strategy: {merge_strategy}",
            f"auto_merge: {'true' if auto_merge else 'false'}",
            "",
            "orchestration:",
            "  test_followup: true",
        ]
    )

    if adapter != "auto":
        lines.extend(
            [
                "",
                "routing:",
                f"  default_adapter: {adapter}",
            ]
        )

    lines.extend(
        [
            "",
            "quality_gates:",
            "  fix_proof: true",
            "",
            "# Roles to use (uncomment to customize):",
            "# team:",
            "#   - backend",
            "#   - frontend",
            "#   - qa",
            "#   - security",
            "",
        ]
    )

    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# CLI command
# ---------------------------------------------------------------------------


@click.command("init-wizard")
@click.option("--dir", "target_dir", default=".", show_default=True, help="Directory to initialise.")
@click.option("--non-interactive", is_flag=True, default=False, help="Use defaults without prompting.")
def init_wizard_cmd(target_dir: str, non_interactive: bool) -> None:
    """Interactive wizard to set up a Bernstein project.

    \b
    Asks questions about your project and generates:
      - .sdd/ directory structure
      - bernstein.yaml configuration file

    \b
    Examples:
      bernstein init-wizard                    # interactive setup
      bernstein init-wizard --non-interactive  # use defaults
    """
    root = Path(target_dir).resolve()

    console.print("\n[bold cyan]Bernstein Project Setup Wizard[/bold cyan]\n")

    # Detect project type
    project_type = detect_project_type(root)
    if project_type != "generic":
        console.print(f"  [green]Detected:[/green] {project_type} project\n")

    if non_interactive:
        goal = f"Improve this {project_type} project"
        max_agents = 3
        budget = 5.0
        adapter = "auto"
        approval = "auto"
    else:
        # Ask questions
        goal = click.prompt(
            "  Project goal",
            default=f"Improve this {project_type} project",
        )

        max_agents = click.prompt(
            "  Max concurrent agents",
            type=int,
            default=3,
        )

        budget = click.prompt(
            "  Budget cap (USD, 0 = unlimited)",
            type=float,
            default=5.0,
        )

        adapter = click.prompt(
            "  Preferred adapter",
            type=click.Choice(["auto", "claude", "codex", "gemini"]),
            default="auto",
        )

        approval = click.prompt(
            "  Approval mode",
            type=click.Choice(["auto", "review", "pr"]),
            default="auto",
        )

    # Create directories
    console.print("\n[bold]Creating workspace...[/bold]")
    for d in SDD_DIRS:
        p = root / d
        p.mkdir(parents=True, exist_ok=True)

    # Write config
    yaml_content = generate_yaml(goal, project_type, max_agents, budget, adapter, approval)
    yaml_path = find_seed_file(root) or (root / "bernstein.yaml")
    wrote_yaml = False
    if yaml_path.exists():
        overwrite = not non_interactive and click.confirm(
            f"  {yaml_path.name} already exists. Overwrite?", default=False
        )
        if not overwrite:
            console.print("[dim]  Skipped bernstein.yaml[/dim]")
        else:
            yaml_path.write_text(yaml_content)
            wrote_yaml = True
            console.print(f"  [green]Updated[/green] {yaml_path.name}")
    else:
        yaml_path.write_text(yaml_content)
        wrote_yaml = True
        console.print(f"  [green]Created[/green] {yaml_path.name}")

    # Write .sdd/config.yaml if not present
    sdd_config = root / ".sdd" / "config.yaml"
    if not sdd_config.exists():
        sdd_config.write_text(
            "# Bernstein workspace config\n"
            "server_port: 8052\n"
            f"max_workers: {max_agents}\n"
            "default_model: sonnet\n"
            "default_effort: high\n"
        )
        console.print("  [green]Created[/green] .sdd/config.yaml")

    # Persist post-completion gate settings where Orchestrator reads them
    # (`.sdd/runtime/run_config.json`) when creating or overwriting the setup.
    if wrote_yaml:
        run_config_path = root / ".sdd" / "runtime" / "run_config.json"
        existing_run_cfg: dict[str, object] = {}
        if run_config_path.exists():
            try:
                loaded = json.loads(run_config_path.read_text(encoding="utf-8"))
                if isinstance(loaded, dict):
                    existing_run_cfg = loaded
            except (OSError, ValueError):
                existing_run_cfg = {}
        existing_run_cfg["approval"] = approval
        existing_run_cfg["merge_strategy"] = "direct" if approval == "auto" else "pr"
        existing_run_cfg["auto_merge"] = approval == "auto"
        run_config_path.parent.mkdir(parents=True, exist_ok=True)
        run_config_path.write_text(json.dumps(existing_run_cfg, indent=2) + "\n", encoding="utf-8")

    # Write .gitignore for runtime
    gi_path = root / ".sdd" / "runtime" / ".gitignore"
    if not gi_path.exists():
        gi_path.parent.mkdir(parents=True, exist_ok=True)
        gi_path.write_text("*.pid\n*.log\n")

    from bernstein.cli.run_bootstrap import ensure_workspace_templates_and_gitignore

    ensure_workspace_templates_and_gitignore(root)

    console.print("\n[bold green]Done![/bold green] Run [cyan]bernstein doctor[/cyan] to verify setup.")
    from bernstein.cli.first_run_readiness import project_handoff

    project_handoff(root).render(console)


@click.command("init-wizard", help="[Deprecated] Use 'bernstein init --wizard' instead.")
@click.option("--dir", "target_dir", default=".", show_default=True, help="Directory to initialise.")
@click.option("--non-interactive", is_flag=True, default=False, help="Use defaults without prompting.")
@click.pass_context
def init_wizard_alias_cmd(ctx: click.Context, target_dir: str, non_interactive: bool) -> None:
    """[Deprecated] Use 'bernstein init --wizard' instead."""
    click.echo(
        "WARNING: 'bernstein init-wizard' is deprecated and will be removed in v4.0.0 (#3140): "
        "use 'bernstein init --wizard' instead.",
        err=True,
    )
    ctx.invoke(init_wizard_cmd, target_dir=target_dir, non_interactive=non_interactive)
