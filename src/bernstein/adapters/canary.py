def load_last_green(path: Path | None = None) -> dict[str, LastGreenEntry]:
    """Load the last-green projection (packaged file by default)."""
    source = path if path is not None else LAST_GREEN_JSON_PATH
    try:
        raw = json.loads(source.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    adapters = raw.get("adapters") if isinstance(raw, dict) else None
    if not isinstance(adapters, dict):
        return {}
    entries: dict[str, LastGreenEntry] = {}
    for name, entry in adapters.items():
        if not isinstance(entry, dict):
            continue
        try:
            entries[str(name)] = LastGreenEntry(
                adapter=str(name),
                binary=str(entry["binary"]),
                version=str(entry["version"]),
                receipt_sha256=str(entry["receipt_sha256"]),
                recorded_at=str(entry["recorded_at"]),
            )
        except KeyError:
            continue
    return entries


def update_last_green(
    entries: dict[str, LastGreenEntry],
    outcome: CanaryOutcome,
    *,
    receipt_sha: str,
    recorded_at: str,
) -> dict[str, LastGreenEntry]:
    """Fold a passing outcome into the last-green projection.

    Only a ``pass`` verdict with a known version updates the projection;
    failures, skips, and below-floor refusals never touch it, so the table
    always names the newest version a receipt actually attested.

    A below-floor version can never enter the projection even if a caller
    somehow presents it as a ``pass`` (#2515): the last-green table is the
    input to the doctor advisory and the ``bernstein doctor`` version-posture
    surface, so a below-floor row there would silently bless a known-unsafe
    version. The guard is a pure function of the advisory floor map, so the
    property "no last-green row references a below-floor version" holds by
    construction.

    Returns:
        A new mapping; the input is not mutated.
    """
    new_entries = entries.copy()
    if outcome.verdict != "pass" or not outcome.installed_version:
        return new_entries

    from bernstein.adapters.advisories import check_adapter_version

    if check_adapter_version(outcome.adapter, outcome.installed_version) is not None:
        # Below its security floor: refuse to advance last-green onto it.
        return new_entries
    new_entries[outcome.adapter] = LastGreenEntry(
        adapter=outcome.adapter,
        binary=outcome.binary,
        version=outcome.installed_version,
        receipt_sha256=receipt_sha,
        recorded_at=recorded_at,
    )
    return new_entries


def save_last_green(path: Path, entries: dict[str, LastGreenEntry]) -> None:
    """Persist the last-green projection atomically, sorted by adapter."""
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = {
        "schema_version": CANARY_SCHEMA_VERSION,
        "adapters": {
            name: {
                "binary": entry.binary,
                "version": entry.version,
                "receipt_sha256": entry.receipt_sha256,
                "recorded_at": entry.recorded_at,
            }
            for name, entry in sorted(entries.items())
        },
    }
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp.replace(path)


def _parse_recorded_at(value: str) -> datetime | None:
    """Parse a last-green ``recorded_at`` stamp, tolerating a trailing ``Z``.

    Returns ``None`` for an unparseable value (treated as stale by callers:
    a timestamp that cannot be read cannot be proven fresh).
    """
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed if parsed.tzinfo is not None else parsed.replace(tzinfo=UTC)


def last_green_is_stale(
    recorded_at: str,
    *,
    now: datetime,
    max_age_days: int = LAST_GREEN_STALE_DAYS,
) -> bool:
    """Return whether a last-green row is older than ``max_age_days``.

    Time is injected (``now``) so the decision is deterministic and testable;
    the canary passes its run timestamp and the doctor passes ``datetime.now``.
    An unparseable ``recorded_at`` is treated as stale (fail-visible).
    """
    recorded = _parse_recorded_at(recorded_at)
    if recorded is None:
        return True
    return (now - recorded).days > max_age_days


def render_last_green_table(entries: dict[str, LastGreenEntry], *, now: datetime | None = None) -> str:
    """Render the per-adapter last-green table as Markdown.

    Rows sort by adapter name so regeneration is deterministic; each row
    names the receipt hash prefix that attested it. A row whose
    ``recorded_at`` is older than :data:`LAST_GREEN_STALE_DAYS` (as of
    ``now``) is annotated ``(stale)`` so a frozen row stops reading as
    automation-fresh. ``now`` is injected for deterministic tests and set to
    the run timestamp by the canary; it defaults to the current UTC time.
    """
    current = now if now is not None else datetime.now(UTC)
    lines = [
        "| Adapter | Binary | Last-green version | Verified | Receipt |",
        "|---|---|---|---|---|",
    ]
    if not entries:
        lines.append("| _none yet_ | - | - | - | - |")
    for name in sorted(entries):
        entry = entries[name]
        verified = entry.recorded_at
        if last_green_is_stale(entry.recorded_at, now=current):
            verified = f"{entry.recorded_at} (stale)"
        lines.append(
            f"| {entry.adapter} | `{entry.binary}` | {entry.version} | {verified} | `{entry.receipt_sha256[:12]}` |"
        )
    return "\n".join(lines)


def write_last_green_doc(doc_path: Path, entries: dict[str, LastGreenEntry], *, now: datetime | None = None) -> None:
    """Regenerate the last-green table between the doc's markers.

    Idempotent for a fixed ``now``: regenerating with the same entries and
    timestamp leaves the file byte-identical. Content outside the markers is
    preserved verbatim. ``now`` is threaded into the staleness annotation so
    the regenerated table is a deterministic function of ``(entries, now)``.

    Raises:
        ValueError: If the doc is missing either marker.
    """
    text = doc_path.read_text(encoding="utf-8")
    begin = text.find(LAST_GREEN_BEGIN)
    end = text.find(LAST_GREEN_END)
    if -1 in (begin, end) or end < begin:
        raise ValueError(f"{doc_path} is missing the last-green table markers")
    head = text[: begin + len(LAST_GREEN_BEGIN)]
    tail = text[end:]
    table = render_last_green_table(entries, now=now)
    doc_path.write_text(f"{head}\n{table}\n{tail}", encoding="utf-8")


