# Matrix runner
# ---------------------------------------------------------------------------


def run_matrix(
    targets: tuple[CanaryTarget, ...],
    *,
    receipts_dir: Path,
    state_path: Path,
    last_green_path: Path,
    docs_path: Path | None,
    generated_at: str,
    which: Callable[[str], str | None] | None = None,
    contracts_dir: Path | None = None,
    audit_chain: Any | None = None,
) -> MatrixRunResult:
    """Run the canary matrix end to end (the nightly workflow's core).

    For every target: probe, seal a receipt, fold the outcome into the
    failure-threshold state, and update the last-green projection on a
    pass. When ``docs_path`` is given the last-green table in that doc is
    regenerated. When ``audit_chain`` (an ``AuditChainStore``) is given,
    each receipt hash is mirrored into the HMAC audit chain.

    Returns:
        A :class:`MatrixRunResult` with outcomes, regressions, receipt
        paths, and the threshold-crossing deduped issue payloads.
    """
    result = MatrixRunResult()
    state = load_canary_state(state_path)
    last_green = load_last_green(last_green_path)

    for target in targets:
        outcome = run_canary_target(target, which=which, contracts_dir=contracts_dir)
        result.outcomes.append(outcome)

        receipt = build_canary_receipt(outcome, generated_at=generated_at)
        sha = receipt_sha256(receipt)
        result.receipt_paths.append(write_canary_receipt(receipts_dir, receipt))

        if audit_chain is not None:
            from bernstein.core.security.audit_chain import record_adapter_canary_receipt

            record_adapter_canary_receipt(
                chain=audit_chain,
                adapter=outcome.adapter,
                binary=outcome.binary,
                installed_version=outcome.installed_version,
                verdict=outcome.verdict,
                receipt_sha256=sha,
                failures=list(outcome.failures),
            )

        state, should_open = apply_canary_outcome(state, outcome)
        if outcome.verdict == "fail":
            result.regressions.append(outcome.adapter)
        if should_open:
            result.issues_to_open.append(
                {
                    "title": canary_issue_title(outcome),
                    "body": canary_issue_body(outcome, receipt_sha=sha),
                }
            )
        last_green = update_last_green(last_green, outcome, receipt_sha=sha, recorded_at=generated_at)

    save_canary_state(state_path, state)
    save_last_green(last_green_path, last_green)
    if docs_path is not None:
        write_last_green_doc(docs_path, last_green)
    return result
