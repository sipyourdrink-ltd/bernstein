"""Adapter conformance canary matrix (issue #2368).

Upstream CLI churn lands on users when nothing exercises adapter contracts
continuously: version-floor advisories (see :mod:`advisories`) warn about
known-old versions but cannot catch a fresh upstream release breaking an
adapter contract. The canary closes that gap: a nightly run probes every
primary adapter against whatever upstream version is installed and turns
each probe into a receipt, so adapter breakage becomes our finding instead
of a user's broken unattended run.

Design invariants:

* **Each probe result is a content-addressed receipt.** The receipt's
  canonical JSON bytes hash to its identity; two runs that observed the
  same upstream surface at the same timestamp produce byte-identical
  receipts, and a mutated receipt fails verification exactly like a
  tampered chain entry. Receipts are mirrored into the HMAC audit chain
  via :func:`bernstein.core.security.audit_chain.record_adapter_canary_receipt`.
* **The last-green table is a projection of passing receipts.** Every row
  carries the receipt hash that attested it; the docs table and the
  doctor advisory both read the same projection, never a hand-maintained
  list.
* **Issue automation is threshold-gated and deduped.** One upstream flake
  never opens an issue (two consecutive failures required), and the same
  failure fingerprint never opens two.

The nightly workflow (``.github/workflows/adapter-conformance-canary.yml``)
drives :func:`run_matrix` through ``scripts/adapter_canary.py``.
"""

