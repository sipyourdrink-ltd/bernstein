@dataclass(frozen=True)
class CanaryOutcome:
    """Result of probing one canary target.

    Attributes:
        adapter: Adapter registry key.
        binary: Binary name probed.
        model: Model pinned for the probe.
        goal: The pinned goal text.
        installed_version: Parsed ``--version`` token, or ``None``.
        verdict: ``"pass"`` / ``"fail"`` / ``"skip"`` / ``"refuse"``. A
            ``refuse`` verdict marks a below-security-floor version the canary
            declines to certify (see :data:`refused_below_floor`); it never
            enters the last-green projection and is not an upstream-regression
            signal.
        failures: Conformance failure lines (empty unless ``fail`` /
            ``refuse``).
        transcript: Human-readable probe transcript; rides into the
            regression issue so the finding is reproducible from the
            issue alone.
        security_floor: The adapter's minimum-safe floor when tracked, else
            ``None``. Recorded so the last-green guard can reject a below-floor
            version regardless of the conformance verdict.
        refused_below_floor: Whether this outcome is a below-floor refusal.
        skip_reason: Stable, path-independent reason for a ``skip`` verdict
            (``None`` for every other verdict). It is the dedupe key for the
            skip-streak escalation (:func:`skip_fingerprint`): the same
            degraded reason repeating night after night fingerprints
            identically, so a chronic skip escalates exactly once. It is
            deliberately *not* folded into the receipt preimage
            (:func:`build_canary_receipt`) -- the human-readable reason
            already rides in ``transcript`` -- so adding it does not perturb
            any receipt hash.
    """

    adapter: str
    binary: str
    model: str
    goal: str
    installed_version: str | None
    verdict: str
    failures: tuple[str, ...] = ()
    transcript: tuple[str, ...] = ()
    security_floor: str | None = None
    refused_below_floor: bool = False
    skip_reason: str | None = None


@dataclass(frozen=True)
class LastGreenEntry:
    """One adapter's newest conformance-verified upstream version.

    Attributes:
        adapter: Adapter registry key.
        binary: Binary the version was probed from.
        version: Newest version that passed the canary.
        receipt_sha256: Content hash of the passing receipt that attested
            this row; the table is a projection of receipts, so every row
            is independently checkable against its receipt file.
        recorded_at: Timestamp the attesting canary run stamped.
    """

    adapter: str
    binary: str
    version: str
    receipt_sha256: str
    recorded_at: str


@dataclass
class MatrixRunResult:
    """Aggregated result of one canary matrix run.

    Attributes:
        outcomes: Per-target outcomes in matrix order.
        regressions: Adapter names whose verdict was ``fail``.
        refusals: Adapter names refused for a below-security-floor version
            (#2515). Distinct from ``regressions``: a refusal is an
            operator-environment issue, not an upstream conformance break.
        issues_to_open: Threshold-crossing, deduped issue payloads
            (``{"title": ..., "body": ...}``) the workflow should open.
        receipt_paths: Receipt files written this run.
    """

    outcomes: list[CanaryOutcome] = field(default_factory=list)
    regressions: list[str] = field(default_factory=list)
    refusals: list[str] = field(default_factory=list)
    issues_to_open: list[dict[str, str]] = field(default_factory=list)
    receipt_paths: list[Path] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Canonical JSON helpers
# ---------------------------------------------------------------------------


def _canonical_bytes(data: dict[str, Any]) -> bytes:
    return json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _sha256_hex(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


# ---------------------------------------------------------------------------
# Probing
# ---------------------------------------------------------------------------


def probe_binary_version(binary_path: str) -> str | None:
    """Return the first dotted-numeric token from ``<binary> --version``.

    Best-effort: any launch failure, timeout, or unparseable output yields
    ``None`` (reported as unknown rather than fabricating a verdict).
    """
    try:
        proc = subprocess.run(
            [binary_path, "--version"],
            capture_output=True,
            text=True,
            timeout=_VERSION_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        # Log the exception type only: --version output on agent CLIs can
        # echo credential-adjacent environment fragments.
        logger.debug("canary: version probe failed for %s (%s)", binary_path, type(exc).__name__)
        return None
    blob = f"{proc.stdout}\n{proc.stderr}"
    match = _VERSION_TOKEN_RE.search(blob)
    return match.group(0) if match else None


def run_canary_target(
    target: CanaryTarget,
    *,
    which: Callable[[str], str | None] | None = None,
    contracts_dir: Path | None = None,
) -> CanaryOutcome:
    """Probe one canary target: version capture plus conformance verdict.

    The conformance verdict reuses the in-process contract check that
    ``bernstein adapters check`` runs (:func:`bernstein.adapters.report.
    check_adapter_in_process`): the installed binary's ``--help`` surface
    is matched against the adapter's declared contract. Any missing
    required flag or subcommand is a ``fail`` -- exactly the drift shape
    a fresh upstream release ships.

    Args:
        target: The matrix row to probe.
        which: ``shutil.which``-shaped resolver; tests inject stubs.
        contracts_dir: Contract fixture override for tests.

    Returns:
        A populated :class:`CanaryOutcome`.
    """
    resolver = which if which is not None else shutil.which
    transcript: list[str] = [f"target: adapter={target.adapter} binary={target.binary} model={target.model}"]

    binary_resolved = resolver(target.binary)
    if binary_resolved is None:
        transcript.append(f"{target.binary}: not on PATH")
        return CanaryOutcome(
            adapter=target.adapter,
            binary=target.binary,
            model=target.model,
            goal=target.goal,
            installed_version=None,
            verdict="skip",
            transcript=tuple(transcript),
            skip_reason="binary not on PATH",
        )

    # Record which file was actually probed. A shadowed or wrong binary on
    # PATH produces an inconclusive skip that is indistinguishable from real
    # drift unless the resolved path is in the receipt (#2842).
    transcript.append(f"{target.binary} resolved: {binary_resolved}")

    installed_version = probe_binary_version(binary_resolved)
    transcript.append(f"{target.binary} --version: {installed_version or 'unknown'}")

    # Security floor gate (#2515): a below-floor upstream version is never
    # certified, regardless of its --help conformance. We refuse before the
    # conformance probe so a known-unsafe binary is not exercised at all, and
    # the refusal receipt (built from this outcome) references the advisory.
    from bernstein.adapters.advisories import check_adapter_version

    floor_hit = check_adapter_version(target.adapter, installed_version)
    if floor_hit is not None:
        transcript.append(
            f"security floor: {installed_version} below {floor_hit.min_safe_version} "
            f"[{floor_hit.advisory_id}]: refusing certification"
        )
        return CanaryOutcome(
            adapter=target.adapter,
            binary=target.binary,
            model=target.model,
            goal=target.goal,
            installed_version=installed_version,
            verdict="refuse",
            failures=(
                f"{installed_version} below security floor {floor_hit.min_safe_version} "
                f"[{floor_hit.advisory_id}]: {floor_hit.note}",
            ),
            transcript=tuple(transcript),
            security_floor=floor_hit.min_safe_version,
            refused_below_floor=True,
        )

    from bernstein.adapters.report import check_adapter_in_process

    payload = check_adapter_in_process(
        target.adapter,
        binary_resolved=binary_resolved,
        contracts_dir=contracts_dir,
    )
    verdict = str(payload.verdict)
    detail = str(payload.detail or "")
    transcript.append(f"conformance: {verdict}" + (f" ({detail})" if detail else ""))

    if verdict == "fail":
        failures = tuple(part.strip() for part in detail.split(";") if part.strip())
        return CanaryOutcome(
            adapter=target.adapter,
            binary=target.binary,
            model=target.model,
            goal=target.goal,
            installed_version=installed_version,
            verdict="fail",
            failures=failures,
            transcript=tuple(transcript),
        )
    if verdict == "ok":
        return CanaryOutcome(
            adapter=target.adapter,
            binary=target.binary,
            model=target.model,
            goal=target.goal,
            installed_version=installed_version,
            verdict="pass",
            transcript=tuple(transcript),
        )
    # The skip reason is the report detail when present (e.g. "probe
    # inconclusive (...)", "no contract", "binary missing"). It is stable for
    # a given adapter on a given host, so the same degraded surface repeating
    # across nights fingerprints identically and the streak escalates exactly
    # once. The resolved path stays out of the reason (it rides in the
    # transcript for forensics) so the dedupe key does not churn on paths.
    return CanaryOutcome(
        adapter=target.adapter,
        binary=target.binary,
        model=target.model,
        goal=target.goal,
        installed_version=installed_version,
        verdict="skip",
        transcript=tuple(transcript),
        skip_reason=detail or "conformance skip",
    )


